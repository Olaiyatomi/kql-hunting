"""Regenerate the site's detection data from an identity-threat-detections checkout.

Usage:
    pip install pyyaml
    python tools/sync_detections.py path/to/identity-threat-detections

Writes:
    data/detections.js  every rule.yml + query.kql, with its test record
    data/attack.js      ATT&CK and ATLAS technique names and tactics

Both files are plain scripts (window.* assignments) so the site works on
GitHub Pages and straight from disk with no build step.
"""

import json
import sys
from pathlib import Path

import yaml

REPO_URL = "https://github.com/Olaiyatomi/identity-threat-detections"
SITE = Path(__file__).resolve().parent.parent


def load_detections(src: Path) -> list[dict]:
    out = []
    for rule_path in sorted((src / "detections").glob("*/rule.yml")):
        folder = rule_path.parent
        rule = yaml.safe_load(rule_path.read_text(encoding="utf-8"))
        query = (folder / rule.get("query", "query.kql")).read_text(encoding="utf-8").strip()
        tests = [
            {
                "name": t["name"],
                "fixtures": sorted((t.get("fixtures") or {}).keys()),
                "rows": (t.get("expect") or {}).get("rows"),
            }
            for t in rule.get("tests", [])
        ]
        out.append(
            {
                "id": rule["id"],
                "kind": "detection",
                "title": rule["title"],
                "status": rule.get("status"),
                "author": rule.get("author"),
                "created": str(rule.get("created", "")),
                "description": " ".join(str(rule.get("description", "")).split()),
                "severity": rule.get("severity"),
                "attack": rule.get("attack", []),
                "atlas": rule.get("atlas", []),
                "tables": rule.get("data_sources", []),
                "products": ["Microsoft Sentinel"],
                "schedule": rule.get("schedule", {}),
                "tuning": rule.get("tuning", {}),
                "falsePositives": rule.get("false_positives", []),
                "triage": rule.get("triage", []),
                "references": rule.get("references", []),
                "tests": tests,
                "query": query,
                "source": f"{REPO_URL}/tree/main/detections/{folder.name}",
            }
        )
    out.sort(key=lambda d: d["id"])
    return out


def load_techniques(src: Path) -> dict:
    attack = json.loads((src / "data" / "attack_index.json").read_text(encoding="utf-8"))
    atlas = json.loads((src / "data" / "atlas_index.json").read_text(encoding="utf-8"))
    techniques = {
        tid: {"name": t["name"], "tactics": t.get("tactics", [])}
        for tid, t in attack["techniques"].items()
        if not t.get("deprecated")
    }
    for tid, t in atlas["techniques"].items():
        techniques[tid] = {"name": t.get("name", tid), "tactics": t.get("tactics", [])}
    return {
        "attackVersion": attack.get("attack_version"),
        "atlasVersion": atlas.get("atlas_version"),
        "techniques": techniques,
    }


def write_js(path: Path, var: str, data) -> None:
    body = json.dumps(data, indent=1, ensure_ascii=False)
    path.write_text(
        f"// Generated by tools/sync_detections.py. Do not edit by hand.\nwindow.{var} = {body};\n",
        encoding="utf-8",
    )


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1])
    if not (src / "detections").is_dir():
        sys.exit(f"{src} does not look like an identity-threat-detections checkout")
    (SITE / "data").mkdir(exist_ok=True)
    detections = load_detections(src)
    write_js(SITE / "data" / "detections.js", "KQL_DETECTIONS", detections)
    write_js(SITE / "data" / "attack.js", "KQL_ATTACK", load_techniques(src))
    print(f"wrote {len(detections)} detections")


if __name__ == "__main__":
    main()
